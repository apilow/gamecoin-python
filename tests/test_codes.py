class RedeemRequestTests(unittest.TestCase):
    def test_path_body_and_idempotency_key(self):
        client, transport, _ = make_client(ok(redemption_json()), ok(redemption_json()))
        client.codes.redeem("ext:user 42/x", "SPRING-2026")
        request = transport.last
        self.assertEqual((request.method, request.url), ("POST", f"{API}/players/ext%3Auser%2042%2Fx/codes/redeem"))
        self.assertEqual(body_of(request), {"code": "SPRING-2026"})
        self.assertEqual(len(request.headers["Idempotency-Key"]), 36)  # a UUID v4 generated by the SDK
        client.codes.redeem("ext:u", "x", idempotency_key="redeem-1")
        self.assertEqual(transport.last.headers["Idempotency-Key"], "redeem-1")

    def test_the_code_is_sent_as_typed(self):
        client, transport, _ = make_client(ok(redemption_json()))
        client.codes.redeem("ext:u", "  spring - 2026 ")  # the server ignores case, spaces and dashes
        self.assertEqual(body_of(transport.last), {"code": "  spring - 2026 "})

    def test_a_plain_player_id_is_accepted(self):
        client, transport, _ = make_client(ok(redemption_json()))
        client.codes.redeem(PLAYER_ID, "X1")
        self.assertEqual(transport.last.url, f"{API}/players/{PLAYER_ID}/codes/redeem")

    def test_bad_arguments_never_reach_the_network(self):
        for call, exception in (
            (lambda c: c.codes.redeem("ext:u", ""), ValueError),
            (lambda c: c.codes.redeem("ext:u", None), TypeError),
            (lambda c: c.codes.redeem("ext:u", 1234), TypeError),
            (lambda c: c.codes.redeem("", "X1"), ValueError),
            (lambda c: c.codes.redeem("ext:u", "X1", idempotency_key=""), ValueError),
            (lambda c: c.codes.redeem("ext:u", "X1", idempotency_key=5), TypeError),
        ):
            client, transport, _ = make_client()
            with self.assertRaises(exception):
                call(client)
            self.assertEqual(transport.requests, [])

    def test_options_are_keyword_only(self):
        client, _, _ = make_client()
        with self.assertRaises(TypeError):
            client.codes.redeem("ext:u", "X1", "key")


class RedemptionParsingTests(unittest.TestCase):
    def test_redemption(self):
        client, _, _ = make_client(ok(redemption_json()))
        redemption = client.codes.redeem("ext:u", "SPRING")
        self.assertEqual(
            redemption,
            Redemption(
                grants=(RedeemedGrant("gems", 50, Balance("gems", 0, 150, 150)),),
                items=(RedeemedItem("potion", 2),),
                skipped=(RedeemedItem("fire-sword", 1),),
                replayed=False,
            ),
        )
        for field in ("grants", "items", "skipped"):
            self.assertIsInstance(getattr(redemption, field), tuple)
        with self.assertRaises(dataclasses.FrozenInstanceError):
            redemption.replayed = True  # type: ignore[misc]

    def test_empty_lists(self):
        client, _, _ = make_client(ok({"grants": [], "items": [], "skipped": []}))
        self.assertEqual(client.codes.redeem("ext:u", "X"), Redemption((), (), (), False))

    def test_replayed_flag(self):
        client, _, _ = make_client(replayed(redemption_json()), ok(redemption_json()))
        self.assertTrue(client.codes.redeem("ext:u", "X", idempotency_key="k").replayed)
        self.assertFalse(client.codes.redeem("ext:u", "X").replayed)

    def test_unknown_fields_are_ignored_and_a_broken_shape_is_an_invalid_response(self):
        data = redemption_json(extra=1)
        data["grants"][0]["extra"] = True
        client, _, _ = make_client(ok(data), ok({"grants": [], "items": []}))
        self.assertEqual(len(client.codes.redeem("ext:u", "X").grants), 1)
        with self.assertRaises(GameCoinError) as caught:
            client.codes.redeem("ext:u", "X")
        self.assertEqual(caught.exception.code, ErrorCode.INVALID_RESPONSE)


class RedeemErrorTests(unittest.TestCase):
    def test_invalid_code_is_never_retried(self):
        client, transport, sleeps = make_client(api_error(400, "VALIDATION_FAILED", "Invalid request", INVALID_CODE))
        with self.assertRaises(GameCoinError) as caught:
            client.codes.redeem("ext:u", "NOPE")
        error = caught.exception
        self.assertEqual((error.code, error.status), (ErrorCode.VALIDATION_FAILED, 400))
        self.assertEqual(error.details["fieldErrors"]["code"], ["CODE_INVALID"])
        self.assertEqual(len(transport.requests), 1)
        self.assertEqual(sleeps, [])

    def test_other_errors_come_through_the_usual_mapping(self):
        for status, code in ((403, ErrorCode.PLAYER_BLOCKED), (409, ErrorCode.LIMIT_REACHED), (409, ErrorCode.CONFLICT)):
            with self.subTest(code=code):
                client, transport, _ = make_client(api_error(status, code, "message"))
                with self.assertRaises(GameCoinError) as caught:
                    client.codes.redeem("ext:u", "X")
                self.assertEqual((caught.exception.code, caught.exception.status), (code, status))
                self.assertEqual(len(transport.requests), 1)

    def test_rate_limited_is_retried_then_reported_with_retry_after(self):
        client, transport, sleeps = make_client(
            api_error(429, ErrorCode.RATE_LIMITED, "Too many requests", headers={"Retry-After": "3"}), ok(redemption_json())
        )
        self.assertEqual(len(client.codes.redeem("ext:u", "X").grants), 1)
        self.assertEqual((len(transport.requests), sleeps), (2, [3.0]))
        client, transport, _ = make_client(
            api_error(429, ErrorCode.RATE_LIMITED, "Too many requests", headers={"Retry-After": "900"})
        )
        with self.assertRaises(GameCoinError) as caught:
            client.codes.redeem("ext:u", "X")
        self.assertEqual((caught.exception.code, caught.exception.retry_after), (ErrorCode.RATE_LIMITED, 900))
        self.assertEqual(len(transport.requests), 1)

    def test_the_key_is_kept_across_retries(self):
        client, transport, _ = make_client(api_error(503, ErrorCode.INTERNAL), ok(redemption_json()))
        client.codes.redeem("ext:u", "X")
        keys = {r.headers["Idempotency-Key"] for r in transport.requests}
        self.assertEqual(len(transport.requests), 2)
        self.assertEqual(len(keys), 1)


class CreatorCodeTests(unittest.TestCase):
    def test_creator_code_in_the_body(self):
        client, transport, _ = make_client(*[ok(CHECKOUT, 201)] * 3)
        client.checkouts.create("ext:u", pack_sku="gems-500")
        self.assertEqual(body_of(transport.last), {"packSku": "gems-500"})  # not sent when absent
        client.checkouts.create("ext:u", pack_sku="gems-500", creator_code="ALICE10")
        self.assertEqual(body_of(transport.last), {"packSku": "gems-500", "creatorCode": "ALICE10"})
        client.checkouts.create("ext:u", pack_sku="gems-500", locale="fr", creator_code="alice 10")
        self.assertEqual(body_of(transport.last), {"packSku": "gems-500", "locale": "fr", "creatorCode": "alice 10"})

    def test_bad_values_are_refused_locally(self):
        for bad, exception in (("", ValueError), (42, TypeError), (b"X", TypeError)):
            client, transport, _ = make_client()
            with self.assertRaises(exception):
                client.checkouts.create("ext:u", pack_sku="p", creator_code=bad)
            self.assertEqual(transport.requests, [])

    def test_a_refused_creator_code(self):
        details = {"fieldErrors": {"creatorCode": ["CODE_INVALID"]}}
        client, transport, _ = make_client(api_error(400, "VALIDATION_FAILED", "Invalid request", details))
        with self.assertRaises(GameCoinError) as caught:
            client.checkouts.create("ext:u", pack_sku="gems-500", creator_code="NOPE")
        self.assertEqual(caught.exception.code, ErrorCode.VALIDATION_FAILED)
        self.assertEqual(caught.exception.details["fieldErrors"]["creatorCode"], ["CODE_INVALID"])
        self.assertEqual(len(transport.requests), 1)  # a 400 is never retried

    def test_order_creator_code(self):
        data = order_json(creatorCode={"code": "ALICE10", "creatorName": "Alice"})
        client, _, _ = make_client(
            ok({"order": data, "checkoutUrl": "https://pay.test/x"}, 201),
            ok(order_json()),
            ok(order_json(creatorCode=None)),
        )
        checkout = client.checkouts.create("ext:u", pack_sku="p", creator_code="ALICE10")
        self.assertEqual(checkout.order.creator_code, OrderCreatorCode("ALICE10", "Alice"))
        self.assertIsNone(client.orders.get(ORDER_ID).creator_code)  # field absent: an older API
        self.assertIsNone(client.orders.get(ORDER_ID).creator_code)  # field null

    def test_a_broken_creator_code_is_an_invalid_response(self):
        client, _, _ = make_client(ok(order_json(creatorCode={"code": "X"})))
        with self.assertRaises(GameCoinError) as caught:
            client.orders.get(ORDER_ID)
        self.assertEqual(caught.exception.code, ErrorCode.INVALID_RESPONSE)


class PackAvailabilityTests(unittest.TestCase):
    @staticmethod
    def catalog_with(**pack_fields):
        data = catalog_json()
        data["packs"][0].update(pack_fields)
        return data

    def test_ordinary_pack_has_no_availability(self):
        client, _, _ = make_client(ok(catalog_json()), ok(self.catalog_with(availability=None)))
        self.assertIsNone(client.catalog.get().packs[0].availability)  # field absent
        self.assertIsNone(client.catalog.get().packs[0].availability)  # field null

    def test_availability_object(self):
        availability = {
            "startsAt": "2026-10-10T08:00:00.000Z",
            "endsAt": "2026-11-01T00:00:00.000Z",
            "remaining": 42,
            "founder": True,
        }
        client, _, _ = make_client(ok(self.catalog_with(availability=availability)))
        pack = client.catalog.get().packs[0]
        self.assertIsInstance(pack, Pack)
        self.assertEqual(
            pack.availability,
            PackAvailability(datetime(2026, 10, 10, 8, 0, tzinfo=UTC), datetime(2026, 11, 1, tzinfo=UTC), 42, True),
        )
        self.assertIsNotNone(pack.availability.starts_at.tzinfo)

    def test_open_ended_and_unlimited(self):
        availability = {"startsAt": None, "endsAt": None, "remaining": None, "founder": False}
        client, _, _ = make_client(ok(self.catalog_with(availability=availability)))
        self.assertEqual(client.catalog.get().packs[0].availability, PackAvailability(None, None, None, False))

    def test_sold_out_is_zero_not_none(self):
        availability = {"startsAt": None, "endsAt": None, "remaining": 0, "founder": True}
        client, _, _ = make_client(ok(self.catalog_with(availability=availability)))
        self.assertEqual(client.catalog.get().packs[0].availability.remaining, 0)

    def test_unknown_fields_are_ignored(self):
        availability = {"startsAt": None, "endsAt": None, "remaining": 3, "founder": False, "sold": 7}
        client, _, _ = make_client(ok(self.catalog_with(availability=availability)))
        self.assertEqual(client.catalog.get().packs[0].availability, PackAvailability(None, None, 3, False))

    def test_broken_availability_is_an_invalid_response(self):
        broken = (
            {"startsAt": "yesterday", "endsAt": None, "remaining": None, "founder": False},
            {"remaining": 1},
            "soon",
        )
        for bad in broken:
            with self.subTest(availability=bad):
                client, _, _ = make_client(ok(self.catalog_with(availability=bad)))
                with self.assertRaises(GameCoinError) as caught:
                    client.catalog.get()
                self.assertEqual(caught.exception.code, ErrorCode.INVALID_RESPONSE)

    def test_prelaunch_and_launch_date(self):
        data = catalog_json()
        data.update(prelaunch=True, launchAt="2026-12-01T09:30:00.000Z")
        client, _, _ = make_client(
            ok(data), ok(catalog_json()), ok({**catalog_json(), "prelaunch": False, "launchAt": None})
        )
        catalog = client.catalog.get()
        self.assertEqual((catalog.prelaunch, catalog.launch_at), (True, datetime(2026, 12, 1, 9, 30, tzinfo=UTC)))
        older = client.catalog.get()  # a game created before sprint 3 may send neither field
        self.assertEqual((older.prelaunch, older.launch_at), (False, None))
        explicit = client.catalog.get()
        self.assertEqual((explicit.prelaunch, explicit.launch_at), (False, None))


class PackErrorTests(unittest.TestCase):
    def test_pack_not_available_exposes_its_window(self):
        details = {"startsAt": "2026-10-10T08:00:00.000Z", "endsAt": None}
        client, transport, sleeps = make_client(api_error(409, "PACK_NOT_AVAILABLE", "Pack not available", details))
        with self.assertRaises(GameCoinError) as caught:
            client.checkouts.create("ext:u", pack_sku="founder")
        error = caught.exception
        self.assertEqual((error.code, error.status), (ErrorCode.PACK_NOT_AVAILABLE, 409))
        self.assertEqual(error.details, details)
        self.assertEqual((error.details["startsAt"], error.details["endsAt"]), ("2026-10-10T08:00:00.000Z", None))
        self.assertEqual((len(transport.requests), sleeps), (1, []))  # a 409 is never retried

    def test_pack_sold_out(self):
        client, transport, _ = make_client(api_error(409, "PACK_SOLD_OUT", "Pack sold out", {"packSku": "founder"}))
        with self.assertRaises(GameCoinError) as caught:
            client.checkouts.create("ext:u", pack_sku="founder")
        self.assertEqual((caught.exception.code, caught.exception.status), (ErrorCode.PACK_SOLD_OUT, 409))
        self.assertEqual(caught.exception.details, {"packSku": "founder"})
        self.assertEqual(len(transport.requests), 1)

    def test_constants(self):
        self.assertEqual(ErrorCode.PACK_NOT_AVAILABLE, "PACK_NOT_AVAILABLE")
        self.assertEqual(ErrorCode.PACK_SOLD_OUT, "PACK_SOLD_OUT")


